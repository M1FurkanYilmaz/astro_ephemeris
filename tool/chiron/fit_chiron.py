#!/usr/bin/env python3
"""Fit piecewise Chebyshev polynomials to the Horizons Chiron states and
generate lib/src/chiron/chiron_table.dart plus the held-out
test fixture.

Usage:
  fit_chiron.py GRID_TXT TLIST_DIR OUT_DART OUT_FIXTURE_CSV_GZ [OUT_COEF_NPY]

GRID_TXT  fetch_horizons.py grid output (2-day states, one integration run)
TLIST_DIR fetch_horizons.py tlist output (random fractional epochs, never fitted)

Per segment and axis: weighted least squares of a degree-DEGREE Chebyshev
series to the positions AND velocities (velocity rows scaled by
SEG_DAYS/2, i.e. d/dx units) at the grid epochs inside the segment plus
PAD_DAYS on each side (the padding steadies the segment ends). Velocity =
derivative of the series. Coefficients are stored losslessly (little-endian
float64, base64).
"""
import base64, glob, gzip, os, sys
import numpy as np
from numpy.polynomial import chebyshev as C

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from chiron_grid import JD_START, SEG_DAYS, N_SEG, DEGREE, JD_END, PAD_DAYS
from parse_horizons import parse, solution_info

RETRIEVED = '2026-11-04'

def _deriv_matrix(n):
    """D such that coefficients of d/dx = D @ c."""
    D = np.zeros((n + 1, n + 1))
    for j in range(n + 1):
        e = np.zeros(n + 1); e[j] = 1.0
        d = C.chebder(e)
        D[:len(d), j] = d
    return D

def fit(grid):
    n = DEGREE
    D = _deriv_matrix(n)
    coef = np.zeros((N_SEG, 3, n + 1))
    w = SEG_DAYS / 2.0
    for s in range(N_SEG):
        a0 = JD_START + s * SEG_DAYS
        m = (grid[:, 0] >= a0 - PAD_DAYS) & (grid[:, 0] <= a0 + SEG_DAYS + PAD_DAYS)
        d = grid[m]
        x = 2.0 * (d[:, 0] - a0) / SEG_DAYS - 1.0
        V = C.chebvander(x, n)
        A = np.vstack([V, V @ D])
        for k in range(3):
            b = np.concatenate([d[:, 1 + k], w * d[:, 4 + k]])
            coef[s, k] = np.linalg.lstsq(A, b, rcond=None)[0]
    return coef

def evaluate(coef, jd):
    """coef[s, k, j] -> (pos[N,3], vel[N,3]) at jd (array), like the Dart code."""
    jd = np.asarray(jd, dtype=float)
    s = np.minimum(((jd - JD_START) // SEG_DAYS).astype(int), N_SEG - 1)
    x = 2.0 * (jd - (JD_START + s * SEG_DAYS)) / SEG_DAYS - 1.0
    pos = np.empty((len(jd), 3)); vel = np.empty((len(jd), 3))
    for i in range(len(jd)):
        for k in range(3):
            c = coef[s[i], k]
            pos[i, k] = C.chebval(x[i], c)
            vel[i, k] = C.chebval(x[i], C.chebder(c)) * 2.0 / SEG_DAYS
    return pos, vel

def report(name, coef, ref):
    pos, vel = evaluate(coef, ref[:, 0])
    dp = np.linalg.norm(pos - ref[:, 1:4], axis=1)
    dv = np.linalg.norm(vel - ref[:, 4:7], axis=1)
    r = np.linalg.norm(ref[:, 1:4], axis=1)
    print(f'{name}: n={len(ref)} |dpos| max {dp.max():.2e} p95 {np.percentile(dp, 95):.2e} AU '
          f'(max {np.max(dp / r) * 206264.806:.1e} arcsec seen from the Sun); '
          f'|dvel| max {dv.max():.2e} AU/d')
    return dp.max(), dv.max()

def main():
    grid_txt, tdir, out_dart, out_fix = sys.argv[1:5]
    grid = parse(grid_txt)
    info = solution_info(grid_txt)
    assert grid[0, 0] == JD_START and grid[-1, 0] == JD_END
    coef = fit(grid)
    if len(sys.argv) > 5:
        np.save(sys.argv[5], coef)
    jump = max(np.abs(C.chebval(1.0, coef[s].T) - C.chebval(-1.0, coef[s + 1].T)).max()
               for s in range(N_SEG - 1))
    tl = np.concatenate([parse(p)[1:] for p in sorted(glob.glob(os.path.join(tdir, 'tlist_*.txt')))])
    for p in sorted(glob.glob(os.path.join(tdir, 'tlist_*.txt'))):
        assert parse(p)[0, 0] == JD_START, 'tlist request without the anchor epoch'
        assert solution_info(p)['soln'] == info['soln']
    print(f'source {info}')
    print(f'segments {N_SEG} x {SEG_DAYS} d, degree {DEGREE}, pad {PAD_DAYS} d: {coef.size} coefficients '
          f'= {coef.size * 8} bytes float64')
    fit_p, fit_v = report('fitted grid epochs', coef, grid)
    hold_p, hold_v = report('held-out random epochs', coef, tl)
    print(f'max segment-joint discontinuity {jump:.2e} AU')

    blob = base64.b64encode(coef.astype('<f8').tobytes()).decode()
    lines = [blob[i:i + 76] for i in range(0, len(blob), 76)]
    with open(out_dart, 'w') as f:
        f.write(f"""// GENERATED FILE - DO NOT EDIT.
// Generated by tool/chiron/fit_chiron.py from data fetched with
// tool/chiron/fetch_horizons.py (see tool/chiron/README.md).
//
// Source: NASA/JPL Horizons On-Line Ephemeris System (Giorgini & JPL Solar
// System Dynamics Group), retrieved {RETRIEVED}. Courtesy NASA/JPL-Caltech.
// Target: {info['target']}, orbit solution {info['soln']} (soln. date
// {info['soln_date']}); planets {info['planets']}, small-body perturbers
// {info['perturbers']}.
// Horizons settings: COMMAND='2060;' EPHEM_TYPE=VECTORS CENTER='500@10'
// REF_PLANE=FRAME REF_SYSTEM=ICRF OUT_UNITS=AU-D VEC_TABLE=2 VEC_CORR=NONE
// TIME_TYPE=TDB, 2-day step, one request.
//
// Layout: heliocentric (Sun body centre) geometric position in AU, ICRF
// axes (= J2000 mean equator, Astronomy Engine EQJ). Segment s covers JD TDB
// [kChironJdStart + s*kChironSegDays, + kChironSegDays], mapped to x in
// [-1, 1]. Per segment, per axis x, y, z: kChironDegree + 1 Chebyshev
// coefficients c0..cN, value = sum c_j T_j(x) (c0 not halved). Stored as
// little-endian IEEE-754 float64, base64.
//
// Fit vs Horizons (3-D position): max {fit_p:.1e} AU at the fitted epochs,
// max {hold_p:.1e} AU at {len(tl)} held-out random epochs; velocity max {max(fit_v, hold_v):.1e} AU/day.

/// First covered instant, JD TDB (1800-01-01 00:00 TDB).
const double kChironJdStart = {JD_START!r};

/// Last covered instant, JD TDB (2201-08-15 00:00 TDB).
const double kChironJdEnd = {JD_END!r};

/// Segment length in days.
const int kChironSegDays = {SEG_DAYS};

/// Number of segments.
const int kChironSegCount = {N_SEG};

/// Chebyshev degree per axis per segment.
const int kChironDegree = {DEGREE};

/// {coef.size} float64 coefficients ({coef.size * 8} bytes), base64.
const String kChironCoefficientsB64 =
""")
        for i, ln in enumerate(lines):
            f.write(f"    '{ln}'" + (';\n' if i == len(lines) - 1 else '\n'))
    with gzip.open(out_fix, 'wt', compresslevel=9) as f:
        f.write(f'# 2060 Chiron, NASA/JPL Horizons (Courtesy NASA/JPL-Caltech), {info["soln"]} '
                f'soln {info["soln_date"]}, retrieved {RETRIEVED}.\n'
                '# Heliocentric (500@10) geometric ICRF, AU and AU/day, JD TDB. '
                'Random epochs, NOT used in the fit.\n'
                '# jd_tdb,x,y,z,vx,vy,vz\n')
        for row in tl:
            f.write('%.6f,' % row[0] + ','.join('%.15e' % v for v in row[1:]) + '\n')
    print('wrote', out_dart, os.path.getsize(out_dart), out_fix, os.path.getsize(out_fix))

if __name__ == '__main__':
    main()
